-- Migration 011: Demote WIX-sourced Accounts back to Leads
--
-- The original CSV import (005/006 migrations) bulk-loaded the Master
-- Database sheet into accounts/contacts without going through the Lead
-- pipeline at all. That sheet's "Lead Source" column shows most of those
-- rows (901 of 1057) came from raw WIX website form fills, never
-- actually verified/qualified — only 156 were real Apollo-sourced
-- prospecting research. Treating all of them as "Accounts" (implying a
-- known, real company relationship) overstated what we actually know.
--
-- This migration:
--   1. For every Account whose name matches the WIX-sourced list below,
--      creates one Lead per existing Contact under it (source =
--      'Wix Website Inquiry'), or one company-level Lead ('-'/'-') if
--      the Account has no Contact on file.
--   2. Re-points any Interaction that referenced that Account/Contact to
--      the new Lead, so logged call/email history isn't silently lost.
--   3. Deletes the migrated Contacts and Accounts (tasks/opportunities
--      under these accounts were confirmed to be zero at the time this
--      migration was written, so nothing else needs re-pointing).
--
-- Accounts sourced from Apollo (156) are left untouched, as are any
-- Accounts not present in the original Master Database sheet at all
-- (e.g. ones created since, like the 4 new Ottawa accounts from the
-- Lead Conversion detail work).
--
-- Run this in the Supabase SQL Editor. It is one transaction — if
-- anything fails partway, the whole thing rolls back automatically.
-- ============================================================

