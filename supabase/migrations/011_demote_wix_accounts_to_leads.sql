  create temporary table wix_accounts on commit drop as
  select a.* from accounts a
  join wix_names w on lower(trim(a.name)) = lower(trim(w.name));

  create temporary table contact_lead_map (
    contact_id uuid,
    account_id uuid,
    lead_id uuid
  ) on commit drop;

  create temporary table account_fallback_lead (
    account_id uuid primary key,
    lead_id uuid
  ) on commit drop;

  -- One Lead per existing Contact under a WIX-sourced Account
  for r in
    select c.id as contact_id, c.first_name, c.last_name, c.email, c.phone, c.title,
           wa.id as account_id, wa.name as company_name, wa.domain, wa.region, wa.owner_id
    from contacts c
    join wix_accounts wa on wa.id = c.account_id
  loop
    insert into leads (
      organization_id, first_name, last_name, email, phone, title,
      company_name, company_domain, region, source, source_detail,
      lifecycle_stage, owner_id
    ) values (
      v_org_id, r.first_name, r.last_name, r.email, r.phone, r.title,
      r.company_name, r.domain, coalesce(r.region, 'US'), 'Wix Website Inquiry',
      'Migrated from WIX-sourced account', 'New', r.owner_id
    )
    returning id into v_lead_id;

    insert into contact_lead_map (contact_id, account_id, lead_id) values (r.contact_id, r.account_id, v_lead_id);

    insert into account_fallback_lead (account_id, lead_id)
    values (r.account_id, v_lead_id)
    on conflict (account_id) do nothing;

    v_contact_leads := v_contact_leads + 1;
  end loop;

  -- One company-level Lead for WIX-sourced Accounts with no Contact on file
  for r in
    select wa.id as account_id, wa.name as company_name, wa.domain, wa.region, wa.owner_id
    from wix_accounts wa
    where not exists (select 1 from contacts c where c.account_id = wa.id)
  loop
    insert into leads (
      organization_id, first_name, last_name, company_name, company_domain,
      region, source, source_detail, lifecycle_stage, owner_id
    ) values (
      v_org_id, '-', '-', r.company_name, r.domain,
      coalesce(r.region, 'US'), 'Wix Website Inquiry',
      'Migrated from WIX-sourced account (no contact on file)', 'New', r.owner_id
    )
    returning id into v_lead_id;

    insert into account_fallback_lead (account_id, lead_id) values (r.account_id, v_lead_id);

    v_company_leads := v_company_leads + 1;
  end loop;

  -- Re-point interactions that referenced a specific migrated Contact
  update interactions i
  set lead_id = m.lead_id
  from contact_lead_map m
  where i.contact_id = m.contact_id;

  -- Re-point remaining account-level interactions (no contact_id) to that
  -- account's first migrated Lead, so they don't go fully orphaned
  update interactions i
  set lead_id = f.lead_id
  from account_fallback_lead f
  where i.account_id = f.account_id
    and i.contact_id is null
    and i.lead_id is null;

  delete from contacts c using wix_accounts wa where c.account_id = wa.id;
  get diagnostics v_deleted_contacts = row_count;

  delete from accounts a using wix_accounts wa where a.id = wa.id;
  get diagnostics v_deleted_accounts = row_count;

  raise notice 'Created % contact-level leads, % company-level leads. Deleted % contacts, % accounts.',
    v_contact_leads, v_company_leads, v_deleted_contacts, v_deleted_accounts;
